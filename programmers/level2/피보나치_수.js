// 처음 풀이 🚫
function solution(n) {
  if (n < 1) return;
  // 틀린 이유 : n-1, n-2는 "인덱스(순서)"일 뿐인데, 이걸 F(n-1), F(n-2) "피보나치 값"이라고 착각해서 그대로 더해버림
  // 예) n=3 이면 a = (3-1)+(3-2) = 2+1 = 3 이 되어버림. 정답은 F(3)=2 인데 완전히 다른 값이 나옴
  // 즉 피보나치의 재귀 관계(F(n) = F(n-1) + F(n-2))를 전혀 계산하지 않고, n 자기 자신으로 산술 연산만 한 것
  const a = (n - 1) + (n - 2);

  return a % 1234567;
}

/* 두 번째 풀이
* 주요 아이디어 : F(0)=0, F(1)=1 부터 시작해서, 반복문으로 하나씩 앞으로 밀면서(F(2), F(3), ...) n번째까지 값을 누적해서 계산한다.
*   - prev, curr 두 변수만 가지고 "바로 이전 두 값"만 기억하면서 앞으로 전진하는 방식 (재귀 호출 없이 반복문으로 구현 -> 느려질 걱정 없음)
*   - 매 단계마다 1234567로 나머지 연산을 해줘서 숫자가 너무 커지는 것을 방지 (나머지 연산은 더하기 전에 해도, 더한 후에 해도 결과가 같음)
* 문제 유형 : 동적 계획법(DP) - 이전 계산 결과를 재사용해서 다음 값을 구함
* 시간 복잡도 : O(n) -> n번 반복하는 for 루프 한 번만 돌림
* 공간 복잡도 : O(1) -> prev, curr, next 등 고정된 개수의 변수만 사용
* */
function secondSolution(n) {
  const MOD = 1234567;
  let prev = 0; // F(0)
  let curr = 1; // F(1)

  // i=2부터 시작해서 n번째 값이 나올 때까지 F(i) = F(i-1) + F(i-2) 를 반복 계산
  for (let i = 2; i <= n; i++) {
    const next = (prev + curr) % MOD; // F(i) = F(i-1) + F(i-2)
    prev = curr; // prev를 한 칸 앞으로 이동 (F(i-1) -> F(i))
    curr = next; // curr를 한 칸 앞으로 이동 (F(i) 값으로 갱신)
  }

  return curr;
}
